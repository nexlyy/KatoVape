// Собирает отчёт о проверках безопасности: прогоняет оба набора и пишет SECURITY.md.
//
// Отчёт нужен не вместо прогона, а вместе с ним: в шапке стоит коммит и дата, поэтому
// видно, к какому состоянию кода относятся цифры. Повторить может кто угодно одной командой,
// и это единственное, что делает отчёт чего-то стоящим.
//
//   npm run security          прогнать и обновить отчёт
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
// pathname приходит с процентными кодами, а в пути к проекту бывает пробел: без разбора
// обратно рабочий каталог не находится и оба набора молча не запускаются.
const at = decodeURIComponent(new URL('.', ROOT).pathname).replace(/^\/([A-Za-z]:)/, '$1');

const run = (cmd, args) => {
  try {
    return { ok: true, out: execFileSync(cmd, args, { cwd: at, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }) };
  } catch (e) {
    return { ok: false, out: (e.stdout || '') + (e.stderr || '') };
  }
};
const git = (args) => { try { return execFileSync('git', args, { cwd: at, encoding: 'utf8' }).trim(); } catch (e) { return 'нет данных'; } };

console.log('прогон набора по исходникам…');
const stat = run(process.execPath, ['--test', 'test/security.test.mjs']);
// node --test печатает итоги строками «ℹ tests 309»
const n = (word) => Number((stat.out.match(new RegExp('^\\S?\\s*' + word + ' (\\d+)', 'm')) || [])[1] || 0);
const total = n('tests');
const pass = n('pass');
const fail = n('fail');
if (!total) { console.error('не разобрал вывод набора:\n' + stat.out.slice(0, 400)); process.exit(2); }

console.log('прогон по боевой базе…');
const live = run(process.execPath, ['tools/security-live.mjs']);
const lm = live.out.match(/проверок: (\d+), прошло: (\d+), провалено: (\d+)/) || [];
const [lTotal, lPass, lFail] = [Number(lm[1] || 0), Number(lm[2] || 0), Number(lm[3] || 0)];

const failedNames = [...stat.out.matchAll(/^✖ (.+?) \(/gm)].map((m) => m[1])
  .filter((x, i, a) => a.indexOf(x) === i);
const liveFailed = [...live.out.matchAll(/^ ДЫРА +(.+?) {2,}/gm)].map((m) => m[1].trim());

const green = fail === 0 && lFail === 0;
const d = new Date();
const day = String(d.getDate()).padStart(2, '0') + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + d.getFullYear();

const md = `# Проверки безопасности KatoVape

Отчёт собран автоматически: \`npm run security\`. Повторить может кто угодно, у кого есть
репозиторий, и получить те же цифры. Ручных правок в этом файле быть не должно.

- **Дата прогона:** ${day}
- **Коммит:** \`${git(['rev-parse', '--short', 'HEAD'])}\` — ${git(['log', '-1', '--pretty=%s'])}
- **Ветка:** ${git(['rev-parse', '--abbrev-ref', 'HEAD'])}
- **Итог:** ${green ? 'все проверки прошли' : 'ЕСТЬ ПРОВАЛЕННЫЕ, смотрите список ниже'}

## Что проверяется

| Набор | Проверок | Прошло | Провалено |
|---|---:|---:|---:|
| По исходникам (\`test/security.test.mjs\`) | ${total} | ${pass} | ${fail} |
| По боевой базе (\`tools/security-live.mjs\`) | ${lTotal} | ${lPass} | ${lFail} |
| **Всего** | **${total + lTotal}** | **${pass + lPass}** | **${fail + lFail}** |

${fail ? '### Провалено по исходникам\n\n' + failedNames.map((x) => '- ' + x).join('\n') + '\n' : ''}${
  lFail ? '### Провалено на боевой базе\n\n' + liveFailed.map((x) => '- ' + x).join('\n') + '\n' : ''}
## Набор по исходникам

Читает миграции, клиентский код, функции и разметку. Проверяет по одному вопросу на объект,
поэтому новая таблица или функция сама расширяет набор: забыть про неё нельзя.

- каждая таблица: включён ли RLS, описан ли доступ политиками, не выдана ли анониму целиком;
- каждая функция с \`security definer\`: задан ли \`search_path\`, назначены ли права;
- служебные функции: закрыты ли от анонима с учётом порядка \`grant\` и \`revoke\`;
- каждый файл, уходящий в браузер: нет ли в нём ключей, токенов и строк подключения;
- поля, которые заполняет покупатель: экранируются ли они в разметке панели;
- каждая страница: политика источников, запрет форм и подмены базового адреса, список хостов;
- функции на сервере: проверка подписи Telegram и Stripe, счёт неудачных входов, расчёт
  суммы заказа на сервере;
- хранилище картинок: тип файла, размер, кто пишет, куда может указывать путь;
- бот: откуда берётся токен, кто допущен к командам управления.

## Набор по боевой базе

Ходит публичным ключом, тем самым, что лежит в странице витрины, и проверяет, что закрытое
в миграциях закрыто и в облаке: каталог читается, а профили, заказы, промокоды, расходы и
журнал не видны; запись в каталог, заказы и админов отбивается; служебные функции отвечают
отказом. Пробы на запись бьют по строке её же значением, поэтому ничего не меняют.

Отдельно: при включённом RLS PostgREST отвечает \`200\` и пустым списком, а не отказом.
Поэтому набор смотрит на тело ответа. Проверка по одному коду ответа объявила бы утечкой
нормально закрытую таблицу — так и вышло на первом прогоне.

## Чего эти проверки не делают

- не заменяют ручной разбор новой функции или интеграции;
- не проверяют стойкость паролей и настройки самого Supabase (почта, ограничения входа);
- не бьют по бот-серверу: он не смотрит наружу и живёт вне репозитория;
- не ищут уязвимости в чужих библиотеках; версии React, Babel и SDK прибиты хешем в разметке,
  но обновлять их надо руками.

## Как повторить

\`\`\`bash
npm run security
\`\`\`

Отдельно:

\`\`\`bash
node --test test/security.test.mjs
node tools/security-live.mjs
\`\`\`
`;

writeFileSync(new URL('SECURITY.md', ROOT), md);
console.log('\n' + '-'.repeat(60));
console.log('по исходникам: ' + pass + '/' + total + ', по боевой базе: ' + lPass + '/' + lTotal);
console.log('отчёт записан в SECURITY.md');
if (!green) {
  console.error('\nЕсть проваленные проверки. Отчёт это честно показывает.');
  process.exit(1);
}
