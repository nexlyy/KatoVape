-- Закупочная цена перестаёт быть видна из витрины.
--
-- Каталог публичный по замыслу: витрина читает его тем же ключом, что лежит в странице.
-- Правило доступа у таблицы одно на всю строку, поэтому колонка cost, добавленная в 0045,
-- уезжала наружу вместе с ценой и остатком. Пока цены закупки не заполнены, наружу уходили
-- пустые значения, и утечки фактически не было. Она началась бы ровно в тот день, когда
-- владелец их проставит.
--
-- Права на отдельные колонки складываются с правом на всю таблицу, а не отменяют его,
-- поэтому сначала забираем общее право у анонима, потом выдаём поимённо всё, кроме cost.
--
-- ВНИМАНИЕ на будущее: новая колонка в products по умолчанию окажется закрытой от витрины.
-- Это безопасная сторона ошибки, но добавляя колонку, нужную покупателю, её надо дописать
-- в этот список. Тест products-columns следит, чтобы список не разошёлся с таблицей.
revoke select on public.products from anon;
grant select (id, city, category, name, brand, flavor, price, qty, nic, updated_at, tiers, hit, labels)
  on public.products to anon;

