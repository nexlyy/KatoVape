-- Гамма вкуса.
--
-- Цвет полоски вкуса витрина подбирала сама: словарь на «арбуз», «мяту» и прочее, а
-- незнакомое название получало оттенок из хеша имени. Оттенок стабильный, но случайный,
-- поэтому новые вкусы регулярно выходили фиолетовыми, и поправить это было негде.
--
-- Теперь гамма — свойство строки вкуса: менеджер выбирает её в панели, пусто значит «по
-- названию», как было раньше. Набор гамм лежит в shared/tints.js и общий у панели с
-- витриной, поэтому здесь только строка с id гаммы, без списка допустимых значений:
-- иначе каждая новая гамма требовала бы миграции. Чужое значение витрина не узнает и
-- спокойно вернётся к угадыванию.

alter table public.products add column if not exists tint text;

-- Ограничение только на длину: id гаммы — короткое латинское слово, всё остальное это
-- либо опечатка, либо попытка записать в колонку что-то постороннее.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'products_tint_key') then
    alter table public.products add constraint products_tint_key
      check (tint is null or tint ~ '^[a-z][a-z0-9_-]{0,23}$');
  end if;
end $$;

-- Права на каталог выданы анониму поимённо по колонкам (0053), и новая колонка по умолчанию
-- оказывается закрытой: витрина просит tint вместе с ценой и остатком, поэтому список прав
-- переписываем целиком, добавив её.
revoke select on public.products from anon;
grant select (id, city, category, name, brand, flavor, price, qty, nic, updated_at, tiers, hit, labels, tint)
  on public.products to anon;

notify pgrst, 'reload schema';
