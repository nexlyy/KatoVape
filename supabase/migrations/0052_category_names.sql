-- Названия категорий в разделе «Менеджеры» под то, как их называет владелец.
--
-- «Под-системы» это слово из каталога, а в разговоре и в договорённостях о проценте они
-- называются вейпами. Снюс во множественном числе по той же причине: в списке ставок рядом
-- стоят «Жидкости» и «Одноразки», и единственное число там выбивалось.
--
-- Меняются только подписи. Идентификаторы категорий (pods, snus) остаются прежними, поэтому
-- ни товары, ни уже заданные ставки не трогаются.
update public.product_categories
   set name_ru = 'Вейпы', name_uk = 'Вейпи', name_pl = 'Vape'
 where id = 'pods';

update public.product_categories
   set name_ru = 'Снюсы', name_uk = 'Снюси'
 where id = 'snus';

